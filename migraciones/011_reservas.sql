-- 011 · Reservas (apartados de clientes con abonos)
create table if not exists reservas (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity,
  cliente_nombre text not null,
  telefono text,
  fecha date not null default current_date,
  producto text not null,
  categorias text[] not null default '{}',
  imagen_url text,
  imagen_path text,
  precio_total numeric(12,2) not null check (precio_total > 0),
  monto_pagado numeric(12,2) not null default 0 check (monto_pagado >= 0),
  notas text,
  estado text generated always as (case when monto_pagado >= precio_total then 'completado' else 'pendiente' end) stored,
  usuario_id uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (monto_pagado <= precio_total)
);
create index if not exists reservas_fecha_idx on reservas (fecha desc);
create index if not exists reservas_estado_idx on reservas (estado);
alter table reservas enable row level security;
drop policy if exists ver_reservas on reservas;
drop policy if exists crear_reservas on reservas;
drop policy if exists editar_reservas on reservas;
drop policy if exists borrar_reservas on reservas;
create policy ver_reservas    on reservas for select to authenticated using (es_usuario_activo());
create policy crear_reservas  on reservas for insert to authenticated with check (es_usuario_activo());
create policy editar_reservas on reservas for update to authenticated using (es_usuario_activo()) with check (es_usuario_activo());
create policy borrar_reservas on reservas for delete to authenticated using (es_admin());
grant select, insert, update, delete on reservas to authenticated;

create or replace function trg_reservas_upd() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists reservas_upd on reservas;
create trigger reservas_upd before update on reservas for each row execute function trg_reservas_upd();

drop trigger if exists bitacora_reservas on reservas;
create trigger bitacora_reservas after insert or update or delete on reservas for each row execute function registrar_bitacora();

-- Fotos de reservas: cualquier usuario activo puede subirlas a la carpeta reservas/ del bucket productos
drop policy if exists fotos_reservas_subir on storage.objects;
drop policy if exists fotos_reservas_borrar on storage.objects;
create policy fotos_reservas_subir on storage.objects for insert to authenticated
  with check (bucket_id = 'productos' and name like 'reservas/%' and es_usuario_activo());
create policy fotos_reservas_borrar on storage.objects for delete to authenticated
  using (bucket_id = 'productos' and name like 'reservas/%' and es_usuario_activo());

-- Vaciar datos de prueba: ahora también puede borrar las reservas
create or replace function reiniciar_datos(p_opciones jsonb, p_confirmacion text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  o_prod boolean := coalesce((p_opciones->>'productos')::boolean, false);
  o_vent boolean := coalesce((p_opciones->>'ventas')::boolean, false);
  o_cli  boolean := coalesce((p_opciones->>'clientes')::boolean, false);
  o_prov boolean := coalesce((p_opciones->>'proveedores')::boolean, false);
  o_fin  boolean := coalesce((p_opciones->>'finanzas')::boolean, false);
  o_hist boolean := coalesce((p_opciones->>'historial')::boolean, false);
  o_res  boolean := coalesce((p_opciones->>'reservas')::boolean, false);
  n int; r jsonb := '{}'::jsonb;
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede vaciar los datos'; end if;
  if coalesce(p_confirmacion,'') <> 'BORRAR TODO' then raise exception 'Falta la confirmación'; end if;
  if o_prod and not o_vent then raise exception 'Para borrar los productos también hay que borrar las ventas'; end if;
  if not (o_prod or o_vent or o_cli or o_prov or o_fin or o_hist or o_res) then raise exception 'No elegiste nada para borrar'; end if;

  if o_vent then
    delete from devolucion_items; delete from devoluciones;
    delete from factura_items; delete from facturas;
    delete from venta_items; delete from ventas; get diagnostics n = row_count; r := r || jsonb_build_object('ventas', n);
    delete from cierres_caja;
    alter table ventas alter column numero restart with 1;
    alter table devoluciones alter column numero restart with 1;
    alter sequence factura_seq restart with 1;
  end if;
  if o_prod then
    delete from descuentos_programados; delete from promo_codigos;
    delete from movimientos_stock; delete from producto_imagenes;
    delete from productos; get diagnostics n = row_count; r := r || jsonb_build_object('productos', n);
  end if;
  if o_res then delete from reservas; get diagnostics n = row_count; r := r || jsonb_build_object('reservas', n); alter table reservas alter column numero restart with 1; end if;
  if o_cli then delete from clientes; get diagnostics n = row_count; r := r || jsonb_build_object('clientes', n); end if;
  if o_prov then delete from proveedores; get diagnostics n = row_count; r := r || jsonb_build_object('proveedores', n); end if;
  if o_fin then
    delete from fin_movimientos; delete from fin_cuentas; delete from fin_banco; delete from capital_movs;
    r := r || jsonb_build_object('finanzas', true);
  end if;
  if o_hist then delete from bitacora; delete from accesos; r := r || jsonb_build_object('historial', true); end if;
  return r;
end $$;
revoke execute on function reiniciar_datos(jsonb, text) from public, anon;
grant execute on function reiniciar_datos(jsonb, text) to authenticated;
