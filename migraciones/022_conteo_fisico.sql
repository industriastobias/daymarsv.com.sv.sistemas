-- 022 · Conteo físico (toma de inventario): comparar lo que dice el sistema con lo que hay en el almacén.
-- Solo el administrador principal puede iniciar, contar, cerrar y ajustar.
create table if not exists inventarios (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity,
  estado text not null default 'abierto' check (estado in ('abierto','cerrado','cancelado')),
  nota text,
  ajustado boolean not null default false,
  no_contados_cero boolean not null default false,
  creado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  cerrado_en timestamptz
);
create unique index if not exists inventarios_uno_abierto on inventarios ((estado)) where estado = 'abierto';

create table if not exists inventario_items (
  id uuid primary key default gen_random_uuid(),
  inventario_id uuid not null references inventarios(id) on delete cascade,
  producto_id uuid not null references productos(id) on delete cascade,
  variante_id uuid references producto_variantes(id) on delete set null,
  nombre text not null,
  color text,
  codigo text,
  codigo_barras text,
  categoria text,
  costo numeric(12,2) not null default 0,
  precio numeric(12,2) not null default 0,
  esperado integer not null default 0,          -- stock del sistema al iniciar
  contado integer check (contado is null or contado >= 0),
  stock_al_contar integer,                      -- stock del sistema en el momento de contar
  contado_en timestamptz,
  contado_por uuid,
  ajuste integer                                -- cuánto se movió el stock al ajustar
);
create index if not exists inv_items_inv on inventario_items (inventario_id);
create unique index if not exists inv_items_uk on inventario_items (inventario_id, producto_id, coalesce(variante_id, '00000000-0000-0000-0000-000000000000'::uuid), coalesce(color,''));

alter table inventarios enable row level security;
alter table inventario_items enable row level security;
drop policy if exists principal_inventarios on inventarios;
drop policy if exists principal_inv_items on inventario_items;
create policy principal_inventarios on inventarios for select to authenticated using (es_principal());
create policy principal_inv_items on inventario_items for select to authenticated using (es_principal());
grant select on inventarios, inventario_items to authenticated;

drop trigger if exists bitacora_inventarios on inventarios;
create trigger bitacora_inventarios after insert or update on inventarios for each row execute function registrar_bitacora();

-- Iniciar: foto del inventario del sistema (cada color es una fila)
create or replace function inventario_iniciar(p_nota text default null) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_n int;
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede hacer el conteo físico'; end if;
  if exists (select 1 from inventarios where estado = 'abierto') then raise exception 'Ya hay un conteo abierto. Ciérralo o cancélalo primero.'; end if;
  insert into inventarios (nota) values (nullif(trim(coalesce(p_nota,'')),'')) returning id into v_id;
  -- productos sin colores
  insert into inventario_items (inventario_id, producto_id, nombre, codigo, codigo_barras, categoria, costo, precio, esperado)
  select v_id, p.id, p.nombre, p.codigo, p.codigo_barras, c.nombre, coalesce(p.precio_costo,0), coalesce(p.precio_venta,0), p.stock
    from productos p left join categorias c on c.id = p.categoria_id
   where p.activo and not exists (select 1 from producto_variantes v where v.producto_id = p.id);
  -- cada color
  insert into inventario_items (inventario_id, producto_id, variante_id, nombre, color, codigo, codigo_barras, categoria, costo, precio, esperado)
  select v_id, p.id, v.id, p.nombre, v.nombre, p.codigo, coalesce(v.codigo_barras, p.codigo_barras), c.nombre, coalesce(p.precio_costo,0), coalesce(p.precio_venta,0), v.stock
    from productos p join producto_variantes v on v.producto_id = p.id left join categorias c on c.id = p.categoria_id
   where p.activo;
  -- unidades "sin color" (stock del producto que no está repartido en colores)
  insert into inventario_items (inventario_id, producto_id, nombre, color, codigo, codigo_barras, categoria, costo, precio, esperado)
  select v_id, p.id, p.nombre, 'Sin color', p.codigo, p.codigo_barras, c.nombre, coalesce(p.precio_costo,0), coalesce(p.precio_venta,0),
         p.stock - (select coalesce(sum(v.stock),0) from producto_variantes v where v.producto_id = p.id)
    from productos p left join categorias c on c.id = p.categoria_id
   where p.activo and exists (select 1 from producto_variantes v where v.producto_id = p.id)
     and p.stock > (select coalesce(sum(v.stock),0) from producto_variantes v where v.producto_id = p.id);
  select count(*) into v_n from inventario_items where inventario_id = v_id;
  if v_n = 0 then raise exception 'No hay productos para contar'; end if;
  return v_id;
end $$;

-- stock del sistema ahora mismo para una fila del conteo
create or replace function _inv_stock_actual(p_prod uuid, p_var uuid, p_color text) returns integer
language sql stable security definer set search_path = public as $$
  select case
    when p_var is not null then (select stock from producto_variantes where id = p_var)
    when p_color is not null then (select stock from productos where id = p_prod) - (select coalesce(sum(stock),0) from producto_variantes where producto_id = p_prod)
    else (select stock from productos where id = p_prod) end
$$;
revoke execute on function _inv_stock_actual(uuid, uuid, text) from public, anon, authenticated;

-- Contar: guarda lo contado y el stock que tenía el sistema en ese momento (null = quitar el conteo)
create or replace function inventario_contar(p_item uuid, p_contado integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare it inventario_items%rowtype; v_s integer;
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede hacer el conteo físico'; end if;
  select i.* into it from inventario_items i join inventarios n on n.id = i.inventario_id where i.id = p_item and n.estado = 'abierto' for update of i;
  if not found then raise exception 'Ese conteo ya no está abierto'; end if;
  if p_contado is not null and p_contado < 0 then raise exception 'La cantidad no puede ser negativa'; end if;
  if p_contado is null then
    update inventario_items set contado = null, stock_al_contar = null, contado_en = null, contado_por = null where id = p_item;
    return jsonb_build_object('contado', null, 'stock_al_contar', null);
  end if;
  v_s := coalesce(_inv_stock_actual(it.producto_id, it.variante_id, it.color), it.esperado);
  update inventario_items set contado = p_contado, stock_al_contar = v_s, contado_en = now(), contado_por = auth.uid() where id = p_item;
  return jsonb_build_object('contado', p_contado, 'stock_al_contar', v_s);
end $$;

-- Cerrar: opcionalmente ajusta el stock del sistema a lo contado (sin pisar las ventas hechas durante el conteo)
create or replace function inventario_cerrar(p_inv uuid, p_ajustar boolean default false, p_no_contados_cero boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare n inventarios%rowtype; it record; v_act integer; v_base integer; v_diff integer; v_new integer; v_ps integer; v_aj int := 0; v_u int := 0;
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede hacer el conteo físico'; end if;
  select * into n from inventarios where id = p_inv for update;
  if not found or n.estado <> 'abierto' then raise exception 'Ese conteo ya no está abierto'; end if;
  if p_ajustar then
    for it in select * from inventario_items where inventario_id = p_inv order by id loop
      if it.contado is null and not p_no_contados_cero then continue; end if;
      v_act := coalesce(_inv_stock_actual(it.producto_id, it.variante_id, it.color), 0);
      if it.contado is null then v_diff := -v_act;                       -- no contado = 0 unidades
      else v_diff := it.contado - coalesce(it.stock_al_contar, it.esperado); end if;
      if v_diff = 0 then update inventario_items set ajuste = 0 where id = it.id; continue; end if;
      if v_act + v_diff < 0 then v_diff := -v_act; end if;
      if v_diff = 0 then update inventario_items set ajuste = 0 where id = it.id; continue; end if;
      if it.variante_id is not null then
        update producto_variantes set stock = stock + v_diff where id = it.variante_id;
      end if;
      update productos set stock = stock + v_diff where id = it.producto_id returning stock into v_ps;
      insert into movimientos_stock (producto_id, tipo, cantidad, stock_resultante, nota, usuario_id)
      values (it.producto_id, case when v_diff > 0 then 'entrada' else 'salida' end::tipo_movimiento, v_diff, v_ps,
              'Inventario físico #' || n.numero || coalesce(' · ' || nullif(it.color,''), ''), auth.uid());
      update inventario_items set ajuste = v_diff where id = it.id;
      v_aj := v_aj + 1; v_u := v_u + abs(v_diff);
    end loop;
  end if;
  update inventarios set estado = 'cerrado', cerrado_en = now(), ajustado = coalesce(p_ajustar,false), no_contados_cero = coalesce(p_no_contados_cero,false) where id = p_inv;
  return jsonb_build_object('productos_ajustados', v_aj, 'unidades_movidas', v_u);
end $$;

create or replace function inventario_cancelar(p_inv uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede hacer el conteo físico'; end if;
  update inventarios set estado = 'cancelado', cerrado_en = now() where id = p_inv and estado = 'abierto';
  if not found then raise exception 'Ese conteo ya no está abierto'; end if;
end $$;

revoke execute on function inventario_iniciar(text) from public, anon;
revoke execute on function inventario_contar(uuid, integer) from public, anon;
revoke execute on function inventario_cerrar(uuid, boolean, boolean) from public, anon;
revoke execute on function inventario_cancelar(uuid) from public, anon;
grant execute on function inventario_iniciar(text) to authenticated;
grant execute on function inventario_contar(uuid, integer) to authenticated;
grant execute on function inventario_cerrar(uuid, boolean, boolean) to authenticated;
grant execute on function inventario_cancelar(uuid) to authenticated;

-- Vaciar datos: si se borran los productos, también los conteos físicos
create or replace function reiniciar_datos(p_opciones jsonb, p_confirmacion text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  o_prod boolean := coalesce((p_opciones->>'productos')::boolean, false);
  o_vent boolean := coalesce((p_opciones->>'ventas')::boolean, false);
  o_cli  boolean := coalesce((p_opciones->>'clientes')::boolean, false);
  o_prov boolean := coalesce((p_opciones->>'proveedores')::boolean, false);
  o_fin  boolean := coalesce((p_opciones->>'finanzas')::boolean, false);
  o_hist boolean := coalesce((p_opciones->>'historial')::boolean, false);
  o_res  boolean := coalesce((p_opciones->>'reservas')::boolean, false);
  o_cot  boolean := coalesce((p_opciones->>'cotizaciones')::boolean, false);
  n int; r jsonb := '{}'::jsonb;
begin
  if not es_principal() then raise exception 'Solo el administrador principal puede vaciar los datos'; end if;
  if coalesce(p_confirmacion,'') <> 'BORRAR TODO' then raise exception 'Falta la confirmación'; end if;
  if o_prod and not o_vent then raise exception 'Para borrar los productos también hay que borrar las ventas'; end if;
  if not (o_prod or o_vent or o_cli or o_prov or o_fin or o_hist or o_res or o_cot) then raise exception 'No elegiste nada para borrar'; end if;

  if o_vent then
    delete from devolucion_items where true; delete from devoluciones where true;
    delete from factura_items where true; delete from facturas where true;
    delete from venta_items where true; delete from ventas where true; get diagnostics n = row_count; r := r || jsonb_build_object('ventas', n);
    delete from cierres_caja where true;
    alter table ventas alter column numero restart with 1;
    alter table devoluciones alter column numero restart with 1;
    alter sequence factura_seq restart with 1;
  end if;
  if o_prod then
    delete from descuentos_programados where true; delete from promo_codigos where true;
    delete from movimientos_stock where true; delete from producto_imagenes where true;
    delete from inventarios where true;
    delete from productos where true; get diagnostics n = row_count; r := r || jsonb_build_object('productos', n);
  end if;
  if o_res then delete from reservas where true; get diagnostics n = row_count; r := r || jsonb_build_object('reservas', n); alter table reservas alter column numero restart with 1; end if;
  if o_cot then delete from cot_lotes where true; get diagnostics n = row_count; r := r || jsonb_build_object('cotizaciones', n); end if;
  if o_cli then delete from clientes where true; get diagnostics n = row_count; r := r || jsonb_build_object('clientes', n); end if;
  if o_prov then delete from proveedores where true; get diagnostics n = row_count; r := r || jsonb_build_object('proveedores', n); end if;
  if o_fin then
    delete from fin_movimientos where true; delete from fin_cuentas where true; delete from fin_banco where true; delete from capital_movs where true;
    r := r || jsonb_build_object('finanzas', true);
  end if;
  if o_hist then delete from bitacora where true; delete from accesos where true; r := r || jsonb_build_object('historial', true); end if;
  return r;
end $$;
revoke execute on function reiniciar_datos(jsonb, text) from public, anon;
grant execute on function reiniciar_datos(jsonb, text) to authenticated;
